<p>Cessão de direitos é a transferência, de uma pessoa para outra, de direitos que ela tem sobre um bem ou sobre uma obrigação. No mercado imobiliário, o caso mais comum é a cessão dos direitos de quem comprou um imóvel por promessa de compra e venda e ainda não recebeu a escritura definitiva: essa pessoa repassa a outra a posição de comprador.</p>
