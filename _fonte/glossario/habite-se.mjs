<p>Construções e ampliações sem habite-se, ou com habite-se mas sem averbação, são comuns em casas e em imóveis comerciais. O efeito aparece na hora do negócio: a matrícula descreve uma área diferente da real, o financiamento do comprador pode depender da regularização e o valor de mercado pode ser afetado. Em imóveis novos, o habite-se marca o fim da obra e o início de várias etapas de documentação das unidades.</p>
