<p>O tema aparece na venda de lotes em empreendimentos novos, na revenda de lotes por particulares e na intermediação de terrenos em áreas de expansão urbana. Também aparece em ofertas de "lotes" em áreas que ainda não foram regularizadas, situação em que a cautela precisa ser redobrada.</p>

