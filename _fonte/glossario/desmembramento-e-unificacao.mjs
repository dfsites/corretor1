<p><strong>Desmembramento</strong> é a subdivisão de uma gleba em lotes destinados a edificação, com aproveitamento do sistema viário existente, sem abertura de novas vias ou logradouros públicos e sem prolongamento, modificação ou ampliação dos existentes (Lei nº 6.766/1979, art. 2º, § 2º). Quando há abertura de novas vias, trata-se de <a href="/glossario/loteamento/">loteamento</a> (art. 2º, § 1º). Na prática, o termo também é usado para a divisão de um lote em partes menores, situação que segue regras municipais de parcelamento e precisa ser conferida na prefeitura.</p>
