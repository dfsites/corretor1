<p>Não existe percentual universal de divisão entre corretores. A divisão em partes iguais coincide com a regra que o art. 728 do Código Civil aplica quando nada foi ajustado, mas os corretores podem combinar outros critérios. Os fatores que costumam pesar na negociação:</p>
<ul>
