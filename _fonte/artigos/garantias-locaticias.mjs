<p>Pela fiança, uma pessoa garante ao credor que cumprirá a obrigação assumida pelo devedor caso este não a cumpra (Código Civil, art. 818). Na locação, o fiador responde pelas obrigações do locatário nos termos do contrato. Alguns pontos práticos:</p>
