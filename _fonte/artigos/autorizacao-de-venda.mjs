<p>No mercado, o mesmo documento recebe nomes diferentes: autorização de venda, opção de venda, contrato de intermediação, contrato de corretagem. O nome importa menos do que o conteúdo. Um documento chamado "opção" que não traz prazo nem remuneração protege menos do que uma "autorização" completa.</p>

