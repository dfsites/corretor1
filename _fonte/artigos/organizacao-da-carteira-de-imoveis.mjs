<p>Uma carteira maior não significa mais negócios. Cada imóvel exige divulgação, atendimento, visitas e retorno ao proprietário. Se você não consegue dar a atenção combinada a todos, é melhor ter menos imóveis bem trabalhados. Para decidir, observe quanto tempo cada imóvel consome e quantos estão sem retorno ao proprietário em dia.</p>

