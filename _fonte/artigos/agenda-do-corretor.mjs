<p>Prospecção, atualização da carteira e produção de conteúdo raramente têm hora marcada por outra pessoa. Por isso, tendem a ser empurradas pelos compromissos com data. A solução é reservá-las na agenda como blocos fixos, tratados com a mesma seriedade de uma visita.</p>
