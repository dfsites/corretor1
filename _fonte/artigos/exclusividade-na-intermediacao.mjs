<p>Três consequências práticas decorrem desse texto. Primeiro, a exclusividade precisa ser <strong>escrita</strong>; uma combinação verbal não produz o efeito do art. 726. Segundo, ela protege o trabalho do corretor contra a venda feita diretamente pelo proprietário durante o período combinado. Terceiro, essa proteção depende de o corretor efetivamente trabalhar: inércia e ociosidade afastam o direito à remuneração.</p>
