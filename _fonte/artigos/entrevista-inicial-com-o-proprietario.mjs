<p>A primeira conversa com o proprietário define o restante da captação. É nela que o corretor descobre por que o imóvel está à venda, quem decide, em que situação está a documentação e o que o proprietário espera do preço e do trabalho de intermediação. Quem pula essa etapa e vai direto ao valor costuma descobrir os problemas tarde, quando já existe um comprador interessado.</p>
