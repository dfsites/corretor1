<p>Às vezes o proprietário quer encerrar antes do prazo, ou o corretor percebe que não consegue cumprir o que combinou. A autorização pode prever como isso acontece (aviso prévio, forma de comunicação). Se não previr, trate o assunto com o proprietário de forma direta e registre o que for acordado. Quando houver exclusividade com prazo em curso, o encerramento antecipado tem efeitos sobre a remuneração que dependem do que está no documento e das circunstâncias; em caso de divergência, a orientação jurídica é o caminho.</p>

