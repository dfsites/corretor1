<p>Durante a apresentação, fale de mercado e não de opinião pessoal. A frase "o mercado tem pago entre tanto e tanto por imóveis assim" é mais útil que "eu acho que vale menos". Evite também desvalorizar o imóvel: aponte as diferenças em relação aos comparáveis sem julgamentos sobre o gosto do proprietário.</p>
