<ul>
  <li>Concordar com um preço fora da realidade para não perder a captação.</li>
  <li>Apresentar a pesquisa só para um dos titulares.</li>
  <li>Discutir preço sem dados, com base em impressão pessoal.</li>
  <li>Deixar a revisão para quando o imóvel já está parado há muito tempo.</li>
  <li>Propor redução sem antes verificar a qualidade da divulgação.</li>
  <li>Alterar o preço do anúncio sem registro da nova autorização.</li>
</ul>
